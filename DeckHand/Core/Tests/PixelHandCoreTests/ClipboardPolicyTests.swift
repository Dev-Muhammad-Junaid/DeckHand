//  PixelHandCoreTests
//
//  S10: what clipboard text may cross, and the Mac not echoing its own
//  writes.
//

import Foundation
import PixelHandCore
import Testing

@Suite struct ClipboardPolicyTests {
    @Test("Plain text up to the cap is shared")
    func plainText() {
        #expect(ClipboardPolicy.shouldShare(text: "hello", types: ["public.utf8-plain-text"]))
        let atCap = String(repeating: "a", count: ClipboardPolicy.maxTextBytes)
        #expect(ClipboardPolicy.shouldShare(text: atCap, types: []))
    }

    @Test("Empty, missing and oversize text is not")
    func refused() {
        #expect(!ClipboardPolicy.shouldShare(text: nil, types: []))
        #expect(!ClipboardPolicy.shouldShare(text: "", types: []))
        let over = String(repeating: "é", count: ClipboardPolicy.maxTextBytes / 2 + 1)
        #expect(!ClipboardPolicy.shouldShare(text: over, types: []))
    }

    @Test("Concealed, transient and auto-generated items are never shared")
    func privateTypes() {
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                     "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            #expect(!ClipboardPolicy.shouldShare(text: "s3cret", types: ["public.utf8-plain-text", type]), "\(type)")
        }
    }

    @Test("The cap fits the protocol's string limit")
    func capFits() {
        #expect(ClipboardPolicy.maxTextBytes <= ProtocolLimits.maxStringLength)
    }

    @Test("The Mac's own write is not broadcast back")
    func echo() {
        var echo = ClipboardEcho()
        #expect(echo.shouldBroadcast(changeCount: 4))
        echo.wrote(changeCount: 5)
        #expect(!echo.shouldBroadcast(changeCount: 5))
        #expect(echo.shouldBroadcast(changeCount: 6))
    }
}
